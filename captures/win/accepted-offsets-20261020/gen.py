# Build the Windows accepted state "win-offsets-20261020": the V/F point offsets the CPU holds now (verified vf-dump), OC words at stock (0, as after a
# cold boot with BIOS defaults: last-read of boot 5acb..., 2026-10-19 16:12), no residual E OC slot, NO turbo tables, NO ring -> offsets only.
import json, sys, time
from pathlib import Path
sys.path.insert(0, "src")
from arltuner.topology.cpumap import detect
from arltuner.profiles import complete_from_words
from arltuner.profiles.serialize import dump_profile
from arltuner.profiles.fingerprint import parse_fingerprint
from arltuner.guard.policy import fused_top_ratio
from arltuner.helper.ops_accept import _expected_text
W = Path("/home/yk/.hermes/cache/scratch/win"); out = Path(sys.argv[1]); name = "win-offsets-20261020"
d = json.loads((W / "vfdump-win.json").read_text())
fp_text = (W / "fingerprint.json").read_text(); fp = parse_fingerprint(fp_text)
fused = {c.cpu: c.word for c in fp.cpus if c.word is not None}
topo = detect()
words = {}
for u in d["units"]:
    for c in u["cpus"]:
        pts = [int(p["word"], 16) for p in c["points"]]
        top = fused_top_ratio(fused[c["cpu"]])
        pts = [w for w in pts if (w & 0xFF) <= top]          # drop the OC point's table slot (ratio above the top fused ratio: the residual 48x E OC point)
        words[c["cpu"]] = [0] + pts                          # OC word: stock (0)
tops = {cpu: fused_top_ratio(w) for cpu, w in fused.items()}
prof = complete_from_words(topo, name, words, tops, None, None)
header = (f"Accepted {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())} for Windows (offsets only): the V/F point offsets the CPU held on Linux 2026-10-20 "
          "(known-good: P p53p55-fav5675 + E 46x point 6 -100 mV, 15/15 compile), OC words stock, no turbo tables, no ring. Generated by captures/win/accepted-offsets-20261020/gen.py from a verified vf-dump.")
out.mkdir(parents=True, exist_ok=True); (out / "profiles").mkdir(exist_ok=True)
(out / "profiles" / f"{name}.toml").write_text(dump_profile(prof, header))
(out / "CURRENT").write_text(f"# {header}\nprofile = profiles/{name}.toml\n")
(out / "EXPECTED-words.txt").write_text(_expected_text(words, header, None))
(out / "fingerprint.json").write_text(fp_text)
print("units", len(words), "turbo", prof.turbo, "ring", prof.ring)
