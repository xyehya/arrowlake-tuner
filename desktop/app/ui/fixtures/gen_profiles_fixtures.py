#!/usr/bin/env python3
"""Record the profile fixtures from the SIMULATOR helper (G-213). No hardware, no sudo, no installed helper, temp paths only.

    python3 desktop/app/ui/fixtures/gen_profiles_fixtures.py

One simulator run: tune.read -> profiles.save x2 (+ a duplicate name, which the helper refuses) -> profiles.get x2 -> profiles.list, plus the answers of
profiles.accept / profiles.fingerprint of an unprivileged simulator (NO_ACCEPTED_DIR: the simulator keeps no accepted-state directory). It never applies anything, so the
read stays "fresh" for the helper's stale-read check. Writes only the profiles-*.json files named below, then rebuilds fixtures.js from EVERY *.json in this directory (the
format gen_fixtures.py uses), so the other recordings are not re-made: their ids, nonces and timestamps stay as they are.
The accepted state itself cannot be recorded this way: the mock invents it (INVENTED in mock-backend.js). Python stdlib only.
"""
from __future__ import annotations

import grp
import json
import os
import pwd
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_fixtures import HERE, ROOT, Client  # noqa: E402

SAVED = {
    "sim-p0-undervolt": {"scope": "unit", "rows": [{"target": "P0", "offset": {"kind": "points", "mv": {"48": -20, "53": -25}}, "v_target_v": None, "ratio": None}]},
    "sim-e-light": {"scope": "unit", "rows": [{"target": "EC0", "offset": {"kind": "curve", "mv": -15}, "v_target_v": None, "ratio": None}]},
}


def write(name: str, obj: Any) -> None:
    text = json.dumps(obj, indent=1, sort_keys=True) + "\n"
    try:  # the host's boot id is not part of a fixture
        text = text.replace(Path("/proc/sys/kernel/random/boot_id").read_text().strip(), "00000000-0000-4000-8000-000000000000")
    except OSError:
        pass
    (HERE / name).write_text(text, encoding="utf-8")
    print("wrote", name)


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="g213-fixtures-"))
    toml, policy, sock = tmp / "helper.toml", tmp / "policy.toml", tmp / "h.sock"
    user, group = pwd.getpwuid(os.getuid()).pw_name, grp.getgrgid(os.getgid()).gr_name
    toml.write_text('[access]\nusers = ["%s"]\ngroup = "%s"\n' % (user, group), encoding="utf-8")
    os.chmod(toml, 0o600)
    shutil.copy(ROOT / "policies" / "default.toml", policy)
    os.chmod(policy, 0o600)
    proc = subprocess.Popen(
        [sys.executable, "-I", str(ROOT / "tools" / "arltuner-helper.py"), "--sim", "--socket", "--socket-path", str(sock), "--helper-toml", str(toml),
         "--policy", str(policy), "--audit", str(tmp / "audit.jsonl"), "--lock", str(tmp / "lock"), "--state-dir", str(tmp / "state")],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, cwd=tmp)
    try:
        for _ in range(100):
            if sock.exists():
                break
            time.sleep(0.1)
        time.sleep(0.2)
        c = Client(str(sock))
        read = c.call("tune.read")
        assert read.get("ok"), read
        for name, intent in SAVED.items():
            saved = c.call("profiles.save", {"name": name, "intent": intent})
            assert saved.get("ok"), saved
            write(f"profiles-save-{name}.json", {"request": {"op": "profiles.save", "args": {"name": name, "intent": intent}}, "response": saved})
        first = next(iter(SAVED))
        write("profiles-save-exists.json", c.call("profiles.save", {"name": first, "intent": SAVED[first]}))
        for name in SAVED:
            got = c.call("profiles.get", {"name": name})
            assert got.get("ok"), got
            write(f"profiles-get-{name}.json", got)
        write("profiles-saved-list.json", c.call("profiles.list"))
        write("profiles-accept-unavailable.json", c.call("profiles.accept", {"from": "read"}))
        write("profiles-fingerprint-unavailable.json", c.call("profiles.fingerprint"))
    finally:
        proc.terminate()
        try:
            proc.wait(10)
        except subprocess.TimeoutExpired:
            proc.kill()
        shutil.rmtree(tmp, ignore_errors=True)
    bundle = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(HERE.glob("*.json"))}
    (HERE / "fixtures.js").write_text("// GENERATED by gen_fixtures.py from the *.json files next to it. Do not edit.\nexport default " + json.dumps(bundle, indent=1, sort_keys=True) + ";\n", encoding="utf-8")
    print("wrote fixtures.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
